import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
import {topicFor,inspectionTopics} from '../src/inspectionTopics'
import type {Model} from '../src/types'

test('three steps, topic objects, independent feedback, historical exceptions and return location',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-M2-V2';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 expect((await request.post('/api/projects',{data:{model,expected_revision:0}})).ok()).toBeTruthy()
 const plan=await (await request.post(`/api/projects/${model.project.project_id}/plans`,{data:{}})).json()
 const data=await (await request.get(`/api/plans/${plan.id}/checklist`)).json()
 const mapped=data.items.map((i:any)=>topicFor(i,model as unknown as Model))
 expect(mapped).toHaveLength(data.items.length)
 expect(new Set(mapped)).toEqual(new Set(inspectionTopics.map(t=>t[0])))
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'02 引导式安装',exact:true}).click()
 const root=page.getByRole('region',{name:'系统逐项点检'})
 await expect(root.locator('.m2Steps button')).toHaveCount(3)
 await expect(root.locator('.m2Topic')).toHaveCount(4)
 await expect(page.locator('.hero')).toBeHidden()
 await root.locator('.m2Steps button').nth(2).click()
 await root.locator('.m2Topic').filter({hasText:'K03'}).click()
 await expect(root.locator('.m2Object')).toHaveCount(10)
 await expect(root.locator('.m2Guidance details')).toHaveCount(1)
 await root.locator('.m2Object').first().click()
 await expect(root.getByRole('option',{name:'通过（厂家依据待确认）',exact:true})).toBeDisabled()
 await root.getByRole('combobox',{name:'点检结果',exact:true}).selectOption('FAIL')
 await root.getByLabel('记录人',{exact:true}).fill('EPC 自动测试')
 await root.getByLabel('现场说明 / 测量记录 / 不适用原因',{exact:true}).fill('测试异常：映射待核对，非现场事实。')
 await root.getByLabel('现场照片（PNG / JPEG，单张 ≤ 5 MB）').setInputFiles({name:'test-only.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64')})
 await expect(root).toContainText('照片已上传')
 await root.getByRole('button',{name:'保存点检记录',exact:true}).click()
 await expect(root).toContainText('点检记录已保存')
 await root.getByRole('button',{name:'下一未记录项 →',exact:true}).click()
 await expect(root.locator('.m2ObjectHeader')).toContainText('02')
 await expect(root.getByLabel('记录人',{exact:true})).toHaveValue('')
 await root.getByRole('button',{name:'返回对象列表',exact:true}).click()
 await expect(root.locator('.m2Object').first()).toContainText('异常待处理')
 await expect(root.locator('.m2Object').nth(1)).toContainText('未点检')
 await root.getByRole('button',{name:/^异常处理/}).click()
 await expect(root.locator('.m2Exception')).toHaveCount(1)
 await root.getByRole('button',{name:'查看对象与补充反馈 →',exact:true}).click()
 await root.getByRole('combobox',{name:'点检结果',exact:true}).selectOption('PENDING')
 await root.getByRole('button',{name:'保存点检记录',exact:true}).click()
 await expect(root).toContainText('点检记录已保存')
 await page.reload();await page.getByRole('button',{name:'02 引导式安装',exact:true}).click()
 await expect(root.getByLabel('记录人',{exact:true})).toHaveValue('EPC 自动测试')
 await expect(root.locator('.installationPhotos img')).toHaveJSProperty('naturalWidth',1)
 await root.getByRole('button',{name:/^异常处理/}).click()
 await expect(root.locator('.m2Exception')).toContainText('待复核')
 await expect(root.locator('.m2Exception')).toContainText('测试异常')
 await root.locator('.m2Steps button').nth(1).click()
 await root.locator('.m2Topic').filter({hasText:'C01'}).click()
 await expect(root.locator('.m2Object')).toHaveCount(1)
 await root.locator('.m2Object').click()
 await expect(root.locator('.m2ItemTabs button')).toHaveCount(2)
 await root.getByRole('button',{name:'定位 L4 补充 →',exact:true}).click()
 await expect(page.getByRole('heading',{name:'从设备建立端口连接',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'02 引导式安装',exact:true}).click()
 await expect(root.locator('.m2ObjectHeader')).toContainText('METER_PCC.RS485')
 await root.getByRole('button',{name:/^厂家依据待确认/}).click()
 await expect(root.locator('.m2SourceRow')).not.toHaveCount(0)
 await page.setViewportSize({width:800,height:1000})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
})
