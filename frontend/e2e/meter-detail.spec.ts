import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('meter checks carry baseline ports and parameters and preserve independent detail results',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-METER-DETAIL';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'02 引导式安装',exact:true}).click()
 await page.locator('.m2Steps button').nth(1).click()
 await page.locator('.m2Topic').filter({hasText:'C01'}).click()
 await page.locator('.m2Object').click()
 await expect(page.locator('.meterRoute')).toContainText('METER_PCC.RS485')
 await expect(page.locator('.meterRoute')).toContainText('EMS_MASTER.METER_RS485')
 await expect(page.locator('.meterCheck')).toHaveCount(2)
 const ports=page.locator('.meterCheck').first()
 await ports.getByLabel('起点现场设备 / 端子号',{exact:true}).fill('TEST-METER-TERMINAL')
 await ports.getByLabel('终点现场设备 / 端子号',{exact:true}).fill('TEST-EMS-TERMINAL')
 await ports.getByLabel('记录人',{exact:true}).fill('EPC 测试')
 await ports.getByLabel('现场说明 / 测量记录 / 不适用原因',{exact:true}).fill('仅测试持久化，未发生现场作业')
 await ports.getByRole('button',{name:'保存点检记录',exact:true}).click()
 await expect(ports).toContainText('点检记录已保存')
 await expect(page.locator('.meterCheck').nth(1).locator('summary')).toContainText('未记录')
 await page.reload();await page.getByRole('button',{name:'02 引导式安装',exact:true}).click()
 await expect(ports.getByLabel('起点现场设备 / 端子号',{exact:true})).toHaveValue('TEST-METER-TERMINAL')
 await page.locator('.m2ItemTabs button').nth(1).click()
 await expect(page.locator('.meterCheck')).toHaveCount(3)
 await expect(page.locator('.meterTable')).toContainText('波特率')
 await expect(page.locator('.meterTable')).not.toContainText('IP 地址')
 const identity=page.locator('.meterCheck').filter({hasText:'04 iEMS 识别'})
 await expect(identity.getByLabel('实际 SN / 设备标识',{exact:true})).toBeDisabled()
 await identity.getByLabel('已批准的现场测试条件及方法引用',{exact:true}).fill('TEST approved reference')
 await identity.getByLabel('实际 SN / 设备标识',{exact:true}).fill('TEST-SN')
 await identity.getByLabel('记录人',{exact:true}).fill('EPC 测试')
 await identity.getByLabel('现场说明 / 测量记录 / 不适用原因',{exact:true}).fill('仅测试识别记录')
 await identity.getByRole('combobox',{name:'点检结果',exact:true}).selectOption('FAIL')
 await identity.getByRole('button',{name:'保存点检记录',exact:true}).click()
 await expect(identity).toContainText('点检记录已保存')
 await page.getByRole('button',{name:/^异常处理/}).click()
 await expect(page.locator('.m2Exception')).toContainText('仅测试识别记录')
})
