import {test,expect} from '@playwright/test'

test('system settings persist and invalidate prior operating-condition checks',async({page})=>{
 await page.goto('/')
 await page.getByLabel('选择项目').selectOption('LPE-DEMO-LV01-001')
 await page.getByRole('button',{name:'复制为新项目'}).click()
 await expect(page.locator('.projectBar strong')).toHaveText('LV-01 新建样板')
 await page.getByRole('button',{name:/L5 系统设置/}).click()
 await page.getByText('高级设置：通信、逐台参数、现场值与厂家依据',{exact:true}).click()
 await page.locator('[data-comm-node="BESS_01"] > summary').click()
 await expect(page.getByLabel('BESS_01.soc_min planned',{exact:true})).toHaveValue('')
 await expect(page.getByLabel('EMS_01.control_strategy planned',{exact:true})).toHaveValue('')
 await page.getByLabel('BESS_01.ip_address planned',{exact:true}).fill('192.0.2.10')
 await page.getByLabel('BESS_01.ip_address actual',{exact:true}).fill('192.0.2.10')
 await page.getByLabel('BESS_01.soc_min planned',{exact:true}).fill('20')
 await page.getByLabel('BESS_01.soc_min reference',{exact:true}).fill('DEMO-REFERENCE-PENDING')
 await page.getByLabel('EMS_01.control_strategy planned',{exact:true}).fill('TEST-STRATEGY-PENDING-CONFIRMATION')
 await page.getByLabel('nominal_ac_voltage actual',{exact:true}).fill('400')
 await page.getByRole('button',{name:'保存版本',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('已保存不可变版本')
 await page.reload()
 await page.getByRole('button',{name:/L5 系统设置/}).click()
 await page.getByText('高级设置：通信、逐台参数、现场值与厂家依据',{exact:true}).click()
 await page.locator('[data-comm-node="BESS_01"] > summary').click()
 await expect(page.getByLabel('nominal_ac_voltage actual',{exact:true})).toHaveValue('400')
 await expect(page.getByLabel('BESS_01.ip_address planned',{exact:true})).toHaveValue('192.0.2.10')
 await expect(page.getByLabel('BESS_01.soc_min reference',{exact:true})).toHaveValue('DEMO-REFERENCE-PENDING')
 await expect(page.getByLabel('EMS_01.control_strategy planned',{exact:true})).toHaveValue('TEST-STRATEGY-PENDING-CONFIRMATION')
 await expect(page.getByText('待厂家确认',{exact:true}).first()).toBeVisible()
 await expect(page.getByRole('button',{name:/L6 运行条件检查/})).toHaveCount(0)
})
