import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('dynamic scenarios, curve replay, specific fault and field isolation',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-DYN';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 for(const action of ['send','readback'])await request.post(`/api/projects/${model.project.project_id}/iems-configuration`,{data:{mode:'SIMULATION',revision:1,action}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 const panel=page.getByRole('region',{name:'动态联动模拟'})
 for(const scenario of ['load_step','pv_fluctuation','charge_limited']){
  await panel.getByLabel('动态场景',{exact:true}).selectOption(scenario)
  await panel.getByRole('button',{name:'运行动态模拟',exact:true}).click()
  await expect(panel.locator('.dynChart')).toBeVisible()
  await expect(panel.locator('.dynRun')).toContainText('动态演练完成')
  await expect(panel.locator('.dynEvents button')).toHaveCount(2)
 }
 await panel.getByLabel('动态异常注入',{exact:true}).selectOption('bess_block')
 await panel.getByLabel('动态故障设备',{exact:true}).selectOption('BESS_03')
 await panel.getByRole('button',{name:'运行动态模拟',exact:true}).click()
 await expect(panel.getByRole('complementary',{name:'动态异常'})).toContainText('BESS_03')
 await panel.getByRole('button',{name:'定位曲线与设备',exact:true}).first().click()
 await expect(panel.locator('.dynTable tbody tr')).toHaveCount(1)
 await expect(panel.locator('.dynTable tbody tr')).toContainText('BESS_03')
 await panel.getByLabel('动态时间点',{exact:true}).fill('0')
 await expect(panel.locator('.dynTable')).toContainText('该时刻没有注入设备异常')
 await panel.getByRole('button',{name:'回放曲线',exact:true}).click()
 await expect(panel.getByLabel('动态时间点',{exact:true})).not.toHaveValue('0')
 await panel.getByRole('button',{name:'暂停回放',exact:true}).click()
 await page.getByRole('button',{name:'M1 系统建模与设置',exact:true}).click()
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await expect(panel.getByRole('complementary',{name:'动态异常'})).toContainText('BESS_03')
 await page.getByLabel('选择 iEMS 环境',{exact:true}).selectOption('REAL')
 await expect(panel.getByRole('button',{name:'启动现场动态测试',exact:true})).toBeDisabled()
 await expect(panel.locator('.dynChart')).toHaveCount(0)
 await expect(panel).toContainText('没有现场功率曲线')
})
