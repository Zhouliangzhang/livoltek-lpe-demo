import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('per-device state and photos persist independently; unfinished list locates editor',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-TRACK';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'02 厂家技术协同',exact:true}).click();await page.getByRole('button',{name:'更新技术指引',exact:true}).click()
 const tracker=page.getByRole('region',{name:'INSTALL-POSITION 设备回路现场反馈',exact:true})
 await expect(tracker).toContainText('25 项关联')
 await tracker.getByRole('button',{name:'查看对象与反馈 →',exact:true}).click()
 await page.getByRole('button',{name:'INSTALL-POSITION 处理 BESS_01',exact:true}).click()
 await expect(page.locator('#install-note-INSTALL-POSITION')).toBeFocused()
 await page.getByLabel('INSTALL-POSITION 反馈类型',{exact:true}).selectOption('QUESTION')
 await page.locator('#install-note-INSTALL-POSITION').fill('自动测试记录，非真实安装。')
 await page.getByLabel('INSTALL-POSITION 上传现场照片',{exact:true}).setInputFiles({name:'test-not-site.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64')})
 await expect(tracker).toContainText('照片已上传')
 await tracker.getByRole('button',{name:'保存现场反馈',exact:true}).click()
 await expect(tracker).toContainText('现场反馈已保存')
 await page.reload();await page.getByRole('button',{name:'02 厂家技术协同',exact:true}).click()
 await expect(tracker).toContainText('25 项关联')
 await tracker.getByRole('button',{name:'查看对象与反馈 →',exact:true}).click()
 await tracker.getByLabel('仅看技术问题').check()
 await page.getByRole('button',{name:'INSTALL-POSITION 处理 BESS_01',exact:true}).click()
 await expect(tracker.locator('.installationPhotos img')).toHaveCount(1)
 await expect(tracker.locator('.installationPhotos img')).toHaveJSProperty('naturalWidth',1)
 await expect(page.getByRole('region',{name:'INSTALL-EARTH 设备回路现场反馈',exact:true})).not.toContainText('施工完成率')
})
