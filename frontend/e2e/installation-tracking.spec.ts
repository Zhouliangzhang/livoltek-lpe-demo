import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('per-device state and photos persist independently; unfinished list locates editor',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-TRACK';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'02 引导式安装',exact:true}).click();await page.getByRole('button',{name:'生成安装计划',exact:true}).click()
 const tracker=page.getByRole('region',{name:'INSTALL-EARTH 逐项安装记录',exact:true})
 await expect(tracker).toContainText('25 项关联')
 await tracker.getByRole('button',{name:'查看未完成项 →',exact:true}).click()
 await page.getByRole('button',{name:'INSTALL-EARTH 处理 BESS_01',exact:true}).click()
 await expect(page.locator('#install-note-INSTALL-EARTH')).toBeFocused()
 await page.getByLabel('INSTALL-EARTH 安装状态',{exact:true}).selectOption('COMPLETED')
 await page.locator('#install-note-INSTALL-EARTH').fill('自动测试记录，非真实安装。')
 await tracker.getByRole('button',{name:'保存此项安装记录',exact:true}).click()
 await expect(tracker).toContainText('至少一张照片')
 await page.getByLabel('INSTALL-EARTH 上传现场照片',{exact:true}).setInputFiles({name:'test-not-site.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64')})
 await expect(tracker).toContainText('照片已上传')
 await tracker.getByRole('button',{name:'保存此项安装记录',exact:true}).click()
 await expect(tracker).toContainText('1 项已记录完成 · 24 项未完成')
 await page.reload();await page.getByRole('button',{name:'02 引导式安装',exact:true}).click()
 await expect(tracker).toContainText('1 项已记录完成 · 24 项未完成')
 await tracker.getByRole('button',{name:'查看未完成项 →',exact:true}).click()
 await tracker.getByLabel('只看未完成').uncheck()
 await page.getByRole('button',{name:'INSTALL-EARTH 处理 BESS_01',exact:true}).click()
 await expect(tracker.locator('.installationPhotos img')).toHaveCount(1)
 await expect(tracker.locator('.installationPhotos img')).toHaveJSProperty('naturalWidth',1)
 await expect(page.getByRole('region',{name:'INSTALL-PREPOWER 逐项安装记录',exact:true})).toContainText('0 项已记录完成')
})
