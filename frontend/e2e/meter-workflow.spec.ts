import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('sequential meter workflow blocks dependencies, persists evidence and isolates field',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-SEQ';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 const panel=page.getByRole('region',{name:'顺序调试工作台'})
 await expect(panel.getByRole('navigation',{name:'调试顺序'}).getByRole('button')).toHaveCount(14)
 await panel.getByRole('navigation',{name:'调试顺序'}).getByRole('button',{name:/03 零馈表验证/}).click()
 await expect(panel.getByRole('button',{name:'执行本项模拟',exact:true})).toBeDisabled()
 await panel.getByRole('navigation',{name:'调试顺序'}).getByRole('button',{name:/01 调试会话/}).click()
 await panel.getByLabel('调试记录人').fill('EPC 自动测试')
 await panel.getByLabel('调试条件依据').fill('仅合成环境测试，非现场授权')
 await panel.getByRole('checkbox').check()
 await panel.getByRole('button',{name:'建立模拟调试会话'}).click()
 await panel.getByRole('button',{name:'运行模拟 iEMS 自检'}).click()
 await panel.getByRole('button',{name:'进入 03 零馈表验证 →'}).click()
 await expect(panel.getByRole('table')).not.toContainText('IP 地址')
 for(let i=0;i<2;i++){
  await panel.getByRole('button',{name:'执行本项模拟',exact:true}).click()
  await panel.getByRole('button',{name:'下一验证项 →'}).click()
 }
 await panel.getByLabel('计量演练场景').selectOption('stale')
 await panel.getByRole('button',{name:'执行本项模拟',exact:true}).click()
 await expect(panel.getByRole('region',{name:'本项验证结果'})).toContainText('DATA_STALE')
 await expect(panel.getByRole('button',{name:'下一验证项 →'})).toBeDisabled()
 await panel.getByLabel('计量演练场景').selectOption('normal')
 await panel.getByRole('button',{name:'重新执行本项模拟',exact:true}).click()
 await panel.getByRole('button',{name:'下一验证项 →'}).click()
 for(let i=0;i<3;i++){
  await panel.getByRole('button',{name:'执行本项模拟',exact:true}).click()
  if(i<2)await panel.getByRole('button',{name:'下一验证项 →'}).click()
 }
 await expect(panel).toContainText('03 零馈表模拟验证已完成')
 await page.reload();await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await expect(panel).toContainText('03 零馈表模拟验证已完成')
 await panel.getByRole('navigation',{name:'零馈表验证步骤'}).getByRole('button',{name:/03.3 计量数据质量/}).click()
 await panel.getByRole('button',{name:'重新执行本项模拟',exact:true}).click()
 await expect(panel.getByRole('navigation',{name:'零馈表验证步骤'}).getByRole('button',{name:/03.6/})).toContainText('需重新验证')
 await page.getByLabel('选择 iEMS 环境',{exact:true}).selectOption('REAL')
 await expect(panel).toContainText('没有现场测试结果')
 await expect(panel.getByRole('region',{name:'本项验证结果'})).toHaveCount(0)
 await panel.getByRole('navigation',{name:'调试顺序'}).getByRole('button',{name:/03 零馈表验证/}).click()
 await expect(panel.getByRole('button',{name:'现场验证不可用'})).toBeDisabled()
 await expect(panel).toContainText('待厂家确认')
 await expect(page.getByRole('region',{name:'动态联动模拟'})).toHaveCount(0)
})
