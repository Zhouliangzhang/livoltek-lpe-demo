import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('system coordination balances power, localizes failures, persists, isolates field results',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-SYS';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 for(const action of ['send','readback'])await request.post(`/api/projects/${model.project.project_id}/iems-configuration`,{data:{mode:'SIMULATION',revision:1,action}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 const flow=page.getByRole('region',{name:'系统联动测试'})
 for(const scenario of ['surplus','charge_limit','deficit']){
  await flow.getByLabel('联动场景',{exact:true}).selectOption(scenario)
  await flow.getByRole('button',{name:'运行模拟联动测试',exact:true}).click()
  await expect(flow.locator('.coordResult')).toContainText('✓ 模拟联动通过')
  await expect(flow.locator('.coordPower')).toContainText('25')
 }
 await flow.getByLabel('联动场景',{exact:true}).selectOption('pv_reject')
 await flow.getByLabel('联动异常设备',{exact:true}).selectOption('PV_03')
 await flow.getByRole('button',{name:'运行模拟联动测试',exact:true}).click()
 await expect(flow.getByRole('complementary',{name:'联动异常'})).toContainText('PV_03')
 await expect(flow.locator('.coordPower')).toContainText('-22.5')
 await flow.getByRole('button',{name:'查看设备反馈',exact:true}).click()
 await expect(flow.locator('tbody tr')).toHaveCount(1)
 await expect(flow.locator('tbody tr')).toContainText('PV_03')
 await flow.getByLabel('联动场景',{exact:true}).selectOption('meter_stale')
 await flow.getByRole('button',{name:'运行模拟联动测试',exact:true}).click()
 await expect(flow.getByRole('complementary',{name:'联动异常'})).toContainText('METER_DATA_STALE')
 await expect(flow.locator('.coordDevices')).toHaveCount(0)
 await page.getByRole('button',{name:'M1 系统建模与设置',exact:true}).click()
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await expect(flow).toContainText('METER_DATA_STALE')
 await page.getByLabel('选择 iEMS 环境',{exact:true}).selectOption('REAL')
 await expect(flow.getByRole('button',{name:'启动现场联动测试',exact:true})).toBeDisabled()
 await expect(flow.locator('.coordResult')).toHaveCount(0)
 await expect(flow).toContainText('没有现场联动测试结果')
})
