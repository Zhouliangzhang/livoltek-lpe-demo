import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('degraded dispatch, missing feedback and qualified recovery',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-DEGRADE';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 for(const action of ['send','readback'])await request.post(`/api/projects/${model.project.project_id}/iems-configuration`,{data:{mode:'SIMULATION',revision:1,action}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 const panel=page.getByRole('region',{name:'动态联动模拟'})
 await panel.getByLabel('动态场景',{exact:true}).selectOption('charge_limited')
 await panel.getByLabel('动态异常注入',{exact:true}).selectOption('bess_comm_loss')
 await panel.getByLabel('动态故障设备',{exact:true}).selectOption('BESS_03')
 await panel.getByRole('button',{name:'运行动态模拟',exact:true}).click()
 await expect(panel.getByRole('region',{name:'控制降级与恢复结果'})).toContainText('已完成模拟恢复')
 await expect(panel.locator('.dynControlStages button')).toHaveCount(5)
 await panel.getByRole('button',{name:'定位曲线与设备',exact:true}).first().click()
 await expect(panel.locator('.dynTable')).toContainText('无新鲜反馈')
 await expect(panel.locator('.dynTable')).toContainText('无指令送达确认')
 await panel.getByLabel('动态时间点',{exact:true}).fill('56')
 await panel.getByRole('checkbox',{name:'只看当前注入异常',exact:true}).uncheck()
 await expect(panel.locator('tr').filter({hasText:'BESS_03'})).toContainText('恢复观察中')
 await panel.getByLabel('动态时间点',{exact:true}).fill('80')
 await expect(panel.locator('tr').filter({hasText:'BESS_03'})).toContainText('模拟一致')
 await panel.getByLabel('故障恢复模式',{exact:true}).selectOption('persistent')
 await panel.getByRole('button',{name:'运行动态模拟',exact:true}).click()
 await expect(panel.getByRole('region',{name:'控制降级与恢复结果'})).toContainText('维持模拟降级')
 await page.getByLabel('选择 iEMS 环境',{exact:true}).selectOption('REAL')
 await expect(panel.locator('.dynRecovery')).toHaveCount(0)
 await expect(panel.locator('.dynChart')).toHaveCount(0)
 await expect(panel.getByRole('button',{name:'启动现场动态测试',exact:true})).toBeDisabled()
})
