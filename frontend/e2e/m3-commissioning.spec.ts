import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('M1 enters M3; simulation is sequential, failures block, field evidence is isolated',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-M3';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await expect(page.getByRole('button',{name:'02 引导式安装',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:/L5 系统设置/}).click()
 await page.getByRole('button',{name:'完成建模，进入调试与验证',exact:true}).click()
 const flow=page.getByRole('region',{name:'M3 分步调试'})
 await expect(flow.locator('.m3Steps button')).toHaveCount(5)
 await flow.locator('.m3Steps button').nth(3).click()
 await expect(flow.getByRole('button',{name:'运行本步模拟验证',exact:true})).toBeDisabled()
 await flow.locator('.m3Steps button').nth(0).click()
 for(let i=0;i<5;i++){
  if(i===1){await flow.getByLabel('演练场景').selectOption('failure');await flow.getByRole('button',{name:'运行本步模拟验证',exact:true}).click();await expect(flow.locator('.m3Result')).toContainText('模拟故障');await expect(flow.getByRole('button',{name:'下一步验证 →',exact:true})).toBeDisabled();await flow.getByLabel('演练场景').selectOption('normal')}
  await flow.getByRole('button',{name:'运行本步模拟验证',exact:true}).click()
  await expect(flow.locator('.m3Result')).toContainText('模拟通过')
  if(i<4)await flow.getByRole('button',{name:'下一步验证 →',exact:true}).click()
 }
 await expect(flow).toContainText('五步模拟演练完成')
 await page.reload();await page.getByRole('button',{name:'M3 调试与验证',exact:true}).click()
 await expect(flow).toContainText('五步模拟演练完成')
 await flow.getByRole('button',{name:'现场验证',exact:true}).click()
 await expect(flow.locator('.m3Result')).toHaveCount(0)
 await flow.getByLabel('记录人',{exact:true}).fill('测试 EPC')
 await flow.getByLabel('现场实际结果 / 测量值 / 证据引用',{exact:true}).fill('自动测试引用，非真实现场')
 await flow.getByLabel('现场执行条件 / 方法 / 文件引用',{exact:true}).fill('TEST-PERMIT')
 await flow.getByLabel('现场结果',{exact:true}).selectOption('PASS')
 await flow.getByRole('button',{name:'保存本步现场记录',exact:true}).click()
 await flow.getByRole('button',{name:'下一步验证 →',exact:true}).click()
 await expect(flow.getByRole('option',{name:'通过（缺少受控厂家判据，暂不可选）',exact:true})).toBeDisabled()
 await expect(flow.getByRole('button',{name:'下一步验证 →',exact:true})).toBeDisabled()
 await flow.getByRole('button',{name:'模拟演练',exact:true}).click()
 await flow.getByRole('button',{name:'运行本步模拟验证',exact:true}).click()
 await expect(flow.locator('.m3Steps button').nth(1)).toContainText('需重新验证')
 await flow.locator('.m3Steps button').nth(4).click()
 await expect(flow.getByRole('button',{name:'运行本步模拟验证',exact:true})).toBeDisabled()
 await page.setViewportSize({width:800,height:1000})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
})
