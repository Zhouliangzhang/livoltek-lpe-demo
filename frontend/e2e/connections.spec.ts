import {test,expect} from '@playwright/test'
test('equipment catalogue and typed port connections',async({page})=>{
 await page.goto('/')
 await expect(page.getByTestId('topology-canvas').locator('.x6-node')).toHaveCount(10)
 await page.getByRole('button',{name:'复制为新项目'}).click()
 await expect(page.locator('.projectBar strong')).toHaveText('LV-01 新建样板')
 await page.getByLabel('新增设备类型').selectOption('GENERATOR')
 await page.getByRole('button',{name:'＋ 添加设备',exact:true}).click()
 await expect(page.getByTestId('topology-canvas').locator('.x6-node')).toHaveCount(11)
 const id=await page.getByLabel('选择对象').inputValue()
 await page.getByLabel('来源端口',{exact:true}).selectOption(id+'.AC')
 await page.getByLabel('目标端口',{exact:true}).selectOption('EMS_01.ETH1')
 await page.getByRole('button',{name:'添加连接',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Electrical domain conflict')
 await page.getByLabel('目标端口',{exact:true}).selectOption('LV_BUS_01.AC_A')
 await page.getByRole('button',{name:'添加连接',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('已添加连接')
 await page.getByLabel('连接类型').selectOption('COMMUNICATION')
 await page.getByLabel('来源端口',{exact:true}).selectOption(id+'.COM')
 await page.getByLabel('目标端口',{exact:true}).selectOption('EMS_01.ETH1')
 await page.getByRole('button',{name:'添加连接',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('已添加连接')
 await page.getByRole('button',{name:'保存版本',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('已保存不可变版本')
 await page.getByRole('button',{name:/引导式安装/}).click()
 await page.getByRole('button',{name:'生成安装计划'}).click()
 await expect(page.getByText(/第三方接口资料核对 · ASSET_/).last()).toBeVisible()
})
