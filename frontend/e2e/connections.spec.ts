import {test,expect} from '@playwright/test'
test('scan and manual intake persist, reject duplicate SN, and enforce port domains',async({page})=>{
 await page.goto('/')
 await page.getByLabel('选择项目').selectOption('LPE-DEMO-LV01-001')
 await expect(page.getByTestId('topology-canvas').locator('.x6-node').filter({hasNotText:'L1 待补全'})).toHaveCount(10)
 await page.getByRole('button',{name:'复制为新项目'}).click()
 await expect(page.locator('.projectBar strong')).toHaveText('LV-01 新建样板')
 await page.getByRole('button',{name:/L3 型号与资产/}).click()
 await expect(page.getByRole('region',{name:'设备详情',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:/扫码录入 LIVOLTEK/}).click()
 await page.getByLabel('二维码内容').fill('unrecognized-vendor-code')
 await page.getByRole('button',{name:'解析设备',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('未匹配演示主数据')
 await expect(page.getByRole('button',{name:'加入系统模型'})).toBeDisabled()
 await page.getByRole('button',{name:'填入演示二维码'}).click()
 await page.getByRole('button',{name:'解析设备',exact:true}).click()
 await expect(page.getByLabel('manufacturer',{exact:true})).toHaveAttribute('readonly','')
 await expect(page.getByLabel('model',{exact:true})).toHaveAttribute('readonly','')
 await expect(page.getByLabel('sn',{exact:true})).toHaveAttribute('readonly','')
 await expect(page.getByLabel('document',{exact:true})).toHaveAttribute('readonly','')
 await expect(page.getByRole('checkbox',{name:'AC',exact:true})).toBeDisabled()
 await page.getByLabel('location',{exact:true}).fill('BESS room 02')
 await page.getByRole('button',{name:'加入系统模型'}).click()
 await expect(page.getByRole('region',{name:'设备详情',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'查看设备 LIVOLTEK 储能设备',exact:true}).click()
 await expect(page.getByLabel('设备序列号')).toHaveValue('DEMO-SN-0001')
 await expect(page.getByLabel('设备序列号')).toHaveAttribute('readonly','')
 await expect(page.getByLabel('安装位置',{exact:true})).toHaveValue('BESS room 02')
 await page.getByRole('button',{name:'收起详情 ×'}).click()
 await expect(page.getByRole('region',{name:'设备详情',exact:true})).toHaveCount(0)
 await expect(page.getByTestId('topology-canvas').locator('.x6-node').filter({hasNotText:'L1 待补全'})).toHaveCount(11)
 await page.getByRole('button',{name:/扫码录入 LIVOLTEK/}).click()
 await page.getByRole('button',{name:'填入演示二维码'}).click()
 await page.getByRole('button',{name:'解析设备',exact:true}).click()
 await page.getByRole('button',{name:'加入系统模型'}).click()
 await expect(page.getByRole('alert')).toContainText('此 SN 已在项目中录入')
 await page.getByRole('button',{name:'关闭录入'}).click()
 await page.getByRole('button',{name:/手录第三方设备/}).click()
 await page.getByLabel('录入设备名称').fill('Third-party PV acceptance')
 await page.getByLabel('manufacturer',{exact:true}).fill('Demo vendor')
 await page.getByLabel('model',{exact:true}).fill('Demo PV 100 kW')
 await page.getByLabel('sn',{exact:true}).fill('TP-ACCEPTANCE-01')
 await page.getByLabel('document',{exact:true}).fill('DATASHEET-ACCEPTANCE')
 await page.getByRole('button',{name:'加入系统模型'}).click()
 await expect(page.getByTestId('topology-canvas').locator('.x6-node').filter({hasNotText:'L1 待补全'})).toHaveCount(12)
 await expect(page.getByRole('region',{name:'设备详情',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'打开设备 Third-party PV acceptance',exact:true}).click()
 await expect(page.getByLabel('第三方厂家',{exact:true})).toBeEditable()
 await page.getByLabel('第三方厂家',{exact:true}).fill('Updated demo vendor')
 const id=await page.locator('.objectTitle small').innerText()
 await page.getByRole('button',{name:/L4 端口与连接/}).click()
 await expect(page.getByLabel('起点端口',{exact:true})).toBeDisabled()
 await page.getByLabel('起点设备',{exact:true}).selectOption(id)
 await expect(page.getByLabel('起点端口',{exact:true})).toHaveValue(id+'.AC')
 await page.getByLabel('终点设备',{exact:true}).selectOption('EMS_01')
 await expect(page.getByLabel('终点端口',{exact:true})).toBeDisabled()
 await expect(page.getByRole('button',{name:'保存连接并更新拓扑'})).toBeDisabled()
 await page.getByLabel('终点设备',{exact:true}).selectOption('LV_BUS_01')
 await expect(page.getByLabel('终点端口',{exact:true})).toHaveValue('')
 await page.getByLabel('终点端口',{exact:true}).selectOption('LV_BUS_01.AC_A')
 await page.getByRole('button',{name:'保存连接并更新拓扑'}).click()
 await expect(page.getByText(/已保存连接：Third-party PV acceptance/)).toBeVisible()
 await expect(page.getByTestId('topology-canvas').locator('.x6-edge')).toHaveCount(12)
 await expect(page.getByRole('button',{name:'保存版本',exact:true})).toBeDisabled()
 await page.reload()
 await expect(page.getByTestId('topology-canvas').locator('.x6-node').filter({hasNotText:'L1 待补全'})).toHaveCount(12)
 await expect(page.getByTestId('topology-canvas').locator('.x6-edge')).toHaveCount(12)
 await page.getByRole('button',{name:/L3 型号与资产/}).click()
 await expect(page.getByRole('region',{name:'设备详情',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'查看设备 Third-party PV acceptance',exact:true}).click()
 await expect(page.getByLabel('设备序列号')).toHaveValue('TP-ACCEPTANCE-01')
 await expect(page.getByLabel('第三方厂家',{exact:true})).toHaveValue('Updated demo vendor')
 await page.getByRole('button',{name:'资料记录',exact:true}).click()
 await expect(page.getByText('DATASHEET-ACCEPTANCE',{exact:true})).toBeVisible()
})
