import {test,expect} from '@playwright/test'
test('scan and manual intake persist, reject duplicate SN, and enforce port domains',async({page})=>{
 await page.goto('/')
 await expect(page.getByTestId('topology-canvas').locator('.x6-node')).toHaveCount(10)
 await page.getByRole('button',{name:'复制为新项目'}).click()
 await expect(page.locator('.projectBar strong')).toHaveText('LV-01 新建样板')
 await page.getByRole('button',{name:/扫码录入 LIVOLTEK/}).click()
 await page.getByLabel('二维码内容').fill('unrecognized-vendor-code')
 await page.getByRole('button',{name:'解析设备',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('未匹配演示主数据')
 await expect(page.getByRole('button',{name:'加入系统模型'})).toBeDisabled()
 await page.getByRole('button',{name:'填入演示二维码'}).click()
 await page.getByRole('button',{name:'解析设备',exact:true}).click()
 await page.getByLabel('location',{exact:true}).fill('BESS room 02')
 await page.getByRole('button',{name:'加入系统模型'}).click()
 await expect(page.getByLabel('设备序列号')).toHaveValue('DEMO-SN-0001')
 await expect(page.getByTestId('topology-canvas').locator('.x6-node')).toHaveCount(11)
 await page.getByRole('button',{name:/扫码录入 LIVOLTEK/}).click()
 await page.getByRole('button',{name:'填入演示二维码'}).click()
 await page.getByRole('button',{name:'解析设备',exact:true}).click()
 await page.getByRole('button',{name:'加入系统模型'}).click()
 await expect(page.getByRole('alert')).toContainText('此 SN 已在项目中录入')
 await page.getByRole('button',{name:'关闭录入'}).click()
 await page.getByRole('button',{name:/手录第三方设备/}).click()
 await page.getByLabel('录入设备名称').fill('Third-party PV acceptance')
 await page.getByLabel('manufacturer',{exact:true}).fill('Demo vendor')
 await page.getByLabel('model',{exact:true}).fill('Demo PV 100 kW')
 await page.getByLabel('sn',{exact:true}).fill('TP-ACCEPTANCE-01')
 await page.getByLabel('document',{exact:true}).fill('DATASHEET-ACCEPTANCE')
 await page.getByRole('button',{name:'加入系统模型'}).click()
 await expect(page.getByTestId('topology-canvas').locator('.x6-node')).toHaveCount(12)
 const id=await page.locator('.objectTitle small').innerText()
 await page.getByText('维护端口记录与新增连接',{exact:true}).click()
 await page.getByLabel('来源端口',{exact:true}).selectOption(id+'.AC')
 await page.getByLabel('目标端口',{exact:true}).selectOption('EMS_01.ETH1')
 await page.getByRole('button',{name:'添加连接',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Electrical domain conflict')
 await page.getByLabel('目标端口',{exact:true}).selectOption('LV_BUS_01.AC_A')
 await page.getByRole('button',{name:'添加连接',exact:true}).click()
 await expect(page.getByRole('alert')).toHaveCount(0)
 await page.getByRole('button',{name:'保存版本',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('已保存不可变版本')
 await page.reload()
 await expect(page.getByTestId('topology-canvas').locator('.x6-node')).toHaveCount(12)
 await page.getByRole('button',{name:'查看设备 Third-party PV acceptance',exact:true}).click()
 await expect(page.getByLabel('设备序列号')).toHaveValue('TP-ACCEPTANCE-01')
 await page.getByRole('button',{name:'资料记录',exact:true}).click()
 await expect(page.getByText('DATASHEET-ACCEPTANCE',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'运行数据规则检查',exact:true}).click()
 await expect(page.getByText('✓ 数据结构检查通过；不代表工程批准。')).toBeVisible()
})
