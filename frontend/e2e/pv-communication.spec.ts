import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('PV grouped scan preserves individual failures, mapping and field separation',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-PV04';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 const plan=await (await request.post(`/api/projects/${model.project.project_id}/plans`)).json()
 const base=`/api/plans/${plan.id}/meter-workflow`
 const session=await (await request.post(base,{data:{mode:'SIMULATION',edge_id:'CI-072',acknowledged:true,operator:'PV自动测试',reference:'合成数据，非现场许可'}})).json()
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click();await page.getByRole('navigation',{name:'调试顺序'}).getByRole('button',{name:/04 光伏通信/}).click()
 const pv=page.getByRole('region',{name:'光伏通信与身份验证'})
 await expect(pv).toContainText('等待步骤03 PCC验证完成')
 await expect(pv.getByRole('button',{name:'逐台执行模拟验证'})).toBeDisabled()
 for(const step of ['selfcheck','route','identity','quality','reference','stability','complete'])await request.post(base+'/'+session.id+'/run',{data:{step}})
 await pv.getByRole('button',{name:'刷新已保存结果'}).click()
 await expect(pv).toContainText('光伏通信与身份，10台')
 await pv.getByRole('checkbox').check();await pv.getByLabel('光伏演练场景').selectOption('timeout');await pv.getByLabel('光伏异常设备').selectOption('PV_03')
 await pv.getByRole('button',{name:'逐台执行模拟验证'}).click()
 await expect(pv.getByRole('status')).toContainText('1 台异常；其余 9 台')
 await expect(pv.locator('.pvDevice').first()).toContainText('PV_03')
 await expect(pv.getByRole('region',{name:'PV_03 异常处理'})).toContainText('未取得有效路径或通信应答')
 await pv.getByRole('button',{name:'定位处理 PV_03'}).click()
 await expect(page.getByRole('region',{name:'L4 作业区'})).toBeVisible()
 await page.getByRole('button',{name:'返回 M2 调试',exact:true}).click();await page.getByRole('navigation',{name:'调试顺序'}).getByRole('button',{name:/04 光伏通信/}).click()
 await expect(pv.getByRole('status')).toContainText('1 台异常；其余 9 台')
 await pv.getByRole('checkbox').check();await pv.getByRole('button',{name:'逐台执行模拟验证'}).click()
 await expect(pv.getByRole('status')).toContainText('10 台逐台模拟读取完成')
 await pv.locator('.pvDevice').filter({hasText:'PV_03'}).locator('summary').first().click()
 await expect(pv.locator('.pvDevice').filter({hasText:'PV_03'})).toContainText('有功80kW / 可用100kW')
 await page.reload();await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click();await page.getByRole('navigation',{name:'调试顺序'}).getByRole('button',{name:/04 光伏通信/}).click()
 await expect(pv.getByRole('status')).toContainText('10 台逐台模拟读取完成')
 await page.getByLabel('选择 iEMS 环境').selectOption('REAL');await page.getByRole('navigation',{name:'调试顺序'}).getByRole('button',{name:/04 光伏通信/}).click()
 await expect(pv.getByRole('button',{name:'现场验证不可用'})).toBeDisabled()
 await expect(pv.locator('.pvDeviceBody .pvSource')).toHaveCount(0)
})

