import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('grouped fleet executes each device, isolates fault, persists and separates real results',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-FLEET';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 for(const action of ['send','readback'])await request.post(`/api/projects/${model.project.project_id}/iems-configuration`,{data:{mode:'SIMULATION',revision:1,action}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 const fleet=page.getByRole('region',{name:'光储设备自动测试'})
 await expect(fleet.locator('.fleetGroup')).toHaveCount(2)
 await expect(fleet.locator('.fleetDevice')).toHaveCount(0)
 await fleet.getByLabel('模拟故障设备',{exact:true}).selectOption('PV_03')
 await fleet.getByLabel('光储故障项目',{exact:true}).selectOption('limit')
 await fleet.getByRole('button',{name:'自动检测全部光储设备',exact:true}).click()
 await expect(fleet.getByText('本轮已检测 20 / 20 台',{exact:true})).toBeVisible()
 const exceptions=fleet.getByRole('complementary',{name:'光储异常'})
 await expect(exceptions).toContainText('PV_03');await expect(exceptions).toContainText('CONTROL_FEEDBACK_MISMATCH')
 const pv=fleet.getByRole('article',{name:'光伏逆变器测试组'}),bess=fleet.getByRole('article',{name:'储能系统测试组'})
 await expect(pv).toContainText('9 / 10 模拟通过');await expect(bess).toContainText('10 / 10 模拟通过')
 await exceptions.getByRole('button',{name:'查看逐台记录',exact:true}).click()
 await expect(pv.locator('.fleetDevice')).toHaveCount(10)
 await expect(pv.locator('.fleetDetail')).toContainText('未执行 · 前置异常')
 await fleet.getByLabel('模拟故障设备',{exact:true}).selectOption('')
 await pv.locator('.fleetDevice').filter({hasText:'PV_03'}).getByRole('button',{name:'重测此台',exact:true}).click()
 await expect(pv).toContainText('10 / 10 模拟通过');await expect(exceptions).toHaveCount(0)
 await page.getByRole('button',{name:'M1 系统建模与设置',exact:true}).click()
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await expect(pv).toContainText('10 / 10 模拟通过')
 await page.getByLabel('选择 iEMS 环境',{exact:true}).selectOption('REAL')
 await expect(fleet.getByRole('button',{name:'启动现场设备测试',exact:true})).toBeDisabled()
 await expect(fleet).not.toContainText('10 / 10 模拟通过')
 await expect(fleet).toContainText('无现场结果')
})
