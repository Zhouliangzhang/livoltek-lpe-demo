import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('selfcheck distinguishes readonly, blocks faults and recovers same run',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-SELF02';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await page.getByLabel('调试记录人').fill('步骤02自动测试')
 await page.getByLabel('调试条件依据').fill('独立模拟场景，非现场许可')
 await page.getByRole('checkbox').check();await page.getByRole('button',{name:'建立模拟调试会话'}).click()
 const panel=page.getByRole('region',{name:'iEMS 自检及控制权确认'})
 await panel.getByLabel('自检演练场景').selectOption('log_unwritable')
 await panel.getByRole('button',{name:'运行模拟 iEMS 自检'}).click()
 await expect(panel.getByRole('region',{name:'自检异常处理'})).toContainText('日志无法持久化')
 await expect(panel.getByRole('button',{name:'进入 03 零馈表验证 →'})).toHaveCount(0)
 await panel.getByLabel('自检演练场景').selectOption('readonly_only')
 await panel.getByRole('button',{name:'运行模拟 iEMS 自检'}).click()
 await expect(panel).toContainText('模拟可继续')
 await expect(panel).toContainText('保持锁定')
 await expect(panel.getByRole('button',{name:'进入 03 零馈表验证 →'})).toBeVisible()
 await panel.getByText('初始快照、接口及执行范围',{exact:true}).click()
 const before=await panel.locator('.scEvidence').first().innerText()
 await panel.getByRole('button',{name:'查询原运行结果'}).click()
 await expect(panel.locator('.scEvidence').first()).toHaveText(before,{useInnerText:true})
 await page.reload();await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await page.getByRole('button',{name:/02 iEMS 自检/}).click()
 await expect(panel).toContainText('模拟可继续')
 await page.getByLabel('选择 iEMS 环境').selectOption('REAL')
 await page.getByRole('button',{name:/02 iEMS 自检/}).click()
 await expect(panel.getByRole('button',{name:'现场自检不可用'})).toBeDisabled()
 await expect(panel).not.toContainText('模拟可继续')
 await expect(panel).toContainText('未取得现场观测')
})

