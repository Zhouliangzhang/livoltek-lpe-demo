import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('meter details retain M1 identity, block evidence gaps and expose raw phases',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-DETAIL03';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await page.getByLabel('调试记录人').fill('步骤03演练');await page.getByLabel('调试条件依据').fill('合成数据，非现场批准')
 await page.getByRole('checkbox').check();await page.getByRole('button',{name:'建立模拟调试会话'}).click()
 await page.getByRole('button',{name:'运行模拟 iEMS 自检',exact:true}).click()
 await page.getByRole('button',{name:'进入 03 零馈表验证 →'}).click()
 await expect(page.getByRole('region',{name:'M1 零馈表依据'})).toContainText('工程记录 · 非现场实时读回')
 await page.getByRole('button',{name:'执行本项模拟',exact:true}).click();await page.getByRole('button',{name:'下一验证项 →'}).click()
 await page.getByLabel('计量演练场景').selectOption('duplicate_address');await page.getByRole('button',{name:'执行本项模拟',exact:true}).click()
 await expect(page.getByRole('region',{name:'计量异常处理'})).toContainText('同一总线地址出现两个应答身份')
 await expect(page.getByRole('button',{name:'下一验证项 →'})).toBeDisabled()
 await page.getByLabel('计量演练场景').selectOption('normal');await page.getByRole('button',{name:'重新执行本项模拟',exact:true}).click();await page.getByRole('button',{name:'下一验证项 →'}).click()
 await page.getByRole('button',{name:'执行本项模拟',exact:true}).click()
 await expect(page.getByRole('region',{name:'本项验证结果'})).toContainText('总功率与分相关系')
 await page.getByText('三相原始计量 · 电压 / 电流 / 有功',{exact:true}).click()
 await expect(page.getByRole('region',{name:'本项验证结果'})).toContainText('L3')
 await page.getByRole('button',{name:'下一验证项 →'}).click()
 await page.getByLabel('计量演练场景').selectOption('no_reference');await page.getByRole('button',{name:'执行本项模拟',exact:true}).click()
 await expect(page.getByRole('region',{name:'计量异常处理'})).toContainText('证据不足 · 不予放行')
 await expect(page.getByRole('button',{name:'下一验证项 →'})).toBeDisabled()
 await expect(page.getByRole('region',{name:'M1 零馈表依据'})).toContainText('CT 一次/二次倍率')
 await page.getByRole('region',{name:'M1 零馈表依据'}).getByRole('row').filter({hasText:'CT 一次/二次倍率'}).getByRole('button',{name:'定位补充'}).click()
 await expect(page.getByLabel('METER_PCC.ct_ratio actual',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'返回 M2 调试',exact:true}).click()
 await page.getByLabel('计量演练场景').selectOption('normal');await page.getByRole('button',{name:'重新执行本项模拟',exact:true}).click()
 await page.getByRole('button',{name:'下一验证项 →'}).click();await page.getByRole('button',{name:'执行本项模拟',exact:true}).click()
 await page.getByRole('button',{name:'下一验证项 →'}).click();await page.getByRole('button',{name:'执行本项模拟',exact:true}).click()
 await expect(page.getByText('03 零馈表模拟验证已完成',{exact:true})).toBeVisible()
 await page.getByLabel('选择 iEMS 环境').selectOption('REAL');await page.getByRole('button',{name:/03 零馈表验证/}).click()
 await expect(page.getByRole('button',{name:'现场验证不可用'})).toBeDisabled()
 await expect(page.getByRole('region',{name:'本项验证结果'})).toHaveCount(0)
})
