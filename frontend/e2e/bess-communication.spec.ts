import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}

test('BESS conditions, excluded capacity, per-device evidence and field isolation',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-BESS05';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 const plan=await (await request.post(`/api/projects/${model.project.project_id}/plans`)).json()
 const base=`/api/plans/${plan.id}/meter-workflow`
 const session=await (await request.post(base,{data:{mode:'SIMULATION',edge_id:'CI-072',acknowledged:true,operator:'储能自动测试',reference:'合成数据，非现场许可'}})).json()
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 const step=()=>page.getByRole('navigation',{name:'调试顺序'}).getByRole('button',{name:/05 储能通信/}).click()
 await step();const bess=page.getByRole('region',{name:'储能通信与身份验证'})
 await expect(bess.getByRole('button',{name:'逐台执行模拟验证'})).toBeDisabled()
 for(const s of ['selfcheck','route','identity','quality','reference','stability','complete'])await request.post(base+'/'+session.id+'/run',{data:{step:s}})
 await request.post(`/api/plans/${plan.id}/pv-communication`,{data:{session_id:session.id,acknowledged:true,request_id:'pv-ready'}})
 await bess.getByRole('button',{name:'刷新已保存结果'}).click()
 await expect(bess).toContainText('储能通信与身份，10台')
 await bess.getByRole('checkbox').check();await bess.getByLabel('储能演练场景').selectOption('soc_low');await bess.getByLabel('储能异常设备').selectOption('BESS_03')
 await bess.getByRole('button',{name:'逐台执行模拟验证'}).click()
 await expect(bess.getByRole('status')).toContainText('0 台读取异常 · 1 台条件未满足')
 await expect(bess.locator('.pvDevice').first()).toContainText('BESS_03')
 await expect(bess.locator('.pvDevice').first()).toContainText('80 / 0 kW')
 await expect(bess.locator('.pvDevice').first()).toContainText('放电动作：未测试')
 await bess.getByRole('button',{name:'定位处理 BESS_03'}).click()
 await expect(page.getByRole('region',{name:'L5 作业区'})).toBeVisible()
 await page.getByRole('button',{name:'返回 M2 调试',exact:true}).click();await step()
 await bess.getByRole('checkbox').check();await bess.getByLabel('储能演练场景').selectOption('bms_unknown');await bess.getByLabel('储能异常设备').selectOption('BESS_03')
 await bess.getByRole('button',{name:'逐台执行模拟验证'}).click()
 await expect(bess.getByRole('status')).toContainText('1 台读取异常 · 0 台条件未满足')
 await expect(bess).toContainText('720 kW');await expect(bess).toContainText('900 kW')
 await expect(bess.locator('.pvDevice').first()).toContainText('0 / 0 kW')
 await page.reload();await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click();await step()
 await expect(bess.getByRole('status')).toContainText('1 台读取异常')
 await page.getByLabel('选择 iEMS 环境').selectOption('REAL');await step()
 await expect(bess.getByRole('button',{name:'现场验证不可用'})).toBeDisabled()
 await expect(bess.locator('.pvSource')).toHaveCount(0)
})
