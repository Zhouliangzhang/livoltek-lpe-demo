 await page.getByLabel('简化 export_limit',{exact:true}).fill('0')
 await page.getByLabel('统一 battery_operating_mode',{exact:true}).fill('TEST-SELF-CONSUMPTION')
 await page.getByRole('button',{name:/应用到 .* 台计划值/}).click()
