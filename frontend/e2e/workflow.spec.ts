 const node=page.getByTestId('topology-canvas').locator('.x6-node').filter({hasText:'BESS Browser Test'})
 await expect(node).toBeVisible()
 await node.scrollIntoViewIfNeeded()
 const box=await node.boundingBox();if(!box)throw new Error('No graph node')
 await page.mouse.move(box.x+65,box.y+30);await page.mouse.down();await page.mouse.move(box.x+90,box.y+55,{steps:8});await page.mouse.up()
 await expect(page.getByRole('button',{name:'保存版本',exact:true})).toBeDisabled()
 const after=await node.boundingBox();expect(after!.x).toBeCloseTo(box.x,0);expect(after!.y).toBeCloseTo(box.y,0)
 await page.getByRole('button',{name:'放大拓扑',exact:true}).click()
 await expect(page.getByRole('button',{name:'保存版本',exact:true})).toBeDisabled()
 const zoomed=await node.boundingBox();expect(zoomed!.width).toBeGreaterThan(after!.width)
 await page.getByRole('button',{name:'适应全部拓扑',exact:true}).click()
 await page.getByLabel('模拟遥测').selectOption('reverse')
 await expect(page.locator('.flow.reverse')).toHaveCount(1)
 await page.getByLabel('模拟遥测').selectOption('stale')
 await expect(page.locator('.flow')).toHaveCount(0)
 expect((await page.getByTestId('topology-canvas').boundingBox())!.height).toBe(410)
 await page.screenshot({path:'../docs/demo-m1.png',fullPage:true})
 await page.getByRole('button',{name:/L5 系统设置/}).click()
