import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('EPC demand and manufacturer arrangement persist without construction progress',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-COORD';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'02 厂家技术协同',exact:true}).click()
 const card=page.getByRole('region',{name:'厂家技术协同计划',exact:true})
 await card.getByRole('button',{name:'提交协同需求',exact:true}).click();await expect(card).toContainText('请填写联系人')
 await page.getByLabel('协同 EPC 联系人').fill('EPC Demo')
 await page.getByLabel('期望协同时间',{exact:true}).fill('2026-11-10T10:00')
 await page.getByLabel('协同主题',{exact:true}).fill('单台 iEMS 与零馈计量技术支持')
 await page.getByLabel('协同需求说明').fill('模拟需求；请确认远程支持窗口。')
 await page.getByLabel('协同关联对象').selectOption(['EMS_MASTER','BESS_01'])
 await card.getByRole('button',{name:'提交协同需求',exact:true}).click();await expect(card).toContainText('待厂家确认')
 await page.getByLabel('协同操作视角').selectOption('MANUFACTURER')
 await page.getByLabel('厂家协同联系人').fill('Manufacturer Demo')
 await page.getByLabel('厂家确认时间').fill('2026-11-10T11:00')
 await page.getByLabel('厂家安排说明').fill('模拟安排；请提供接口点表。')
 await page.getByRole('button',{name:'保存厂家安排（模拟）',exact:true}).click()
 await expect(card).toContainText('协同安排已确认（演示）')
 await page.reload();await page.getByRole('button',{name:'02 厂家技术协同',exact:true}).click()
 await expect(card).toContainText('模拟安排；请提供接口点表。')
 await card.getByRole('button',{name:'修改协同需求',exact:true}).click()
 await page.getByLabel('协同主题',{exact:true}).fill('更新协同需求')
 await card.getByRole('button',{name:'提交协同需求',exact:true}).click()
 await expect(card.locator('.trackingHeading')).toContainText('待厂家确认')
 await expect(page.getByRole('button',{name:'生成安装计划',exact:true})).toHaveCount(0)
})
