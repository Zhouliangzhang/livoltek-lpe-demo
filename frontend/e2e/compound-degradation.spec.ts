import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('compound rejection retains alarm and prepares unsent support context',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-COMPOUND';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 for(const action of ['send','readback'])await request.post(`/api/projects/${model.project.project_id}/iems-configuration`,{data:{mode:'SIMULATION',revision:1,action}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 const panel=page.getByRole('region',{name:'动态联动模拟'})
 await panel.getByLabel('动态异常注入',{exact:true}).selectOption('meter_pv_reject')
 await panel.getByLabel('动态故障设备',{exact:true}).selectOption('PV_03')
 await panel.getByLabel('故障恢复模式',{exact:true}).selectOption('persistent')
 await panel.getByRole('button',{name:'运行动态模拟',exact:true}).click()
 const alarm=panel.getByRole('region',{name:'复合异常告警'})
 await expect(alarm).toContainText('严重告警 · 零馈无法保证')
 await expect(alarm).toContainText('末点模型馈网 37.5 kW')
 await expect(alarm).toContainText('PV_03')
 await panel.getByLabel('动态时间点',{exact:true}).fill('120')
 await expect(panel.locator('.dynReadout')).toContainText('0 → 107.5 kW')
 await expect(panel.locator('.dynFeedback')).toContainText('有效计量：不可用')
 await alarm.getByRole('button',{name:'准备复合异常厂家协同'}).click()
 await expect(page.getByLabel('评审意见',{exact:true})).toHaveValue(/PV_03/)
 await expect(page.getByLabel('评审意见',{exact:true})).toHaveValue(/37.5/)
 await expect(page.getByLabel('评审意见',{exact:true})).toHaveValue(/模拟，非现场日志/)
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await page.getByLabel('选择 iEMS 环境',{exact:true}).selectOption('REAL')
 await expect(panel.locator('.dynCompoundAlarm,.dynChart')).toHaveCount(0)
 await expect(panel.getByRole('button',{name:'启动现场动态测试',exact:true})).toBeDisabled()
})

