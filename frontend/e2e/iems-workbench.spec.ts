import {test,expect} from '@playwright/test'
import fixture from '../../examples/ci20-pilot.json' with {type:'json'}
test('iEMS workbench configuration loop, automatic tests, fault stop and real isolation',async({page,request})=>{
 const model=structuredClone(fixture);model.project.project_id+='-WB';model.parameters.forEach(p=>{if(p.scope==='PROJECT')p.owner_id=model.project.project_id})
 await request.post('/api/projects',{data:{model,expected_revision:0}})
 await page.goto('/');await page.getByLabel('选择项目').selectOption(model.project.project_id)
 await expect(page.locator('.brand')).toContainText('iEMS 工程工作台')
 await expect(page.locator('.navLinks button')).toHaveCount(4)
 const config=page.getByRole('region',{name:'M1 配置下发与读回'})
 await expect(config).toContainText('尚未下发')
 await config.getByRole('button',{name:'下发到模拟 iEMS',exact:true}).click()
 await expect(config).toContainText('已下发，尚未读回')
 await config.getByLabel('演练读回差异').check()
 await config.getByRole('button',{name:'读取并比较生效配置',exact:true}).click()
 await expect(config).toContainText('模拟读回不一致')
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 const flow=page.getByRole('region',{name:'M2 自动测试'})
 await flow.getByRole('button',{name:'启动模拟 iEMS 自动测试',exact:true}).click()
 await expect(flow.getByRole('alert')).toContainText('模拟下发与读回一致性核对')
 await page.getByRole('button',{name:'M1 系统建模与设置',exact:true}).click()
 await config.getByRole('button',{name:'读取并比较生效配置',exact:true}).click()
 await expect(config).toContainText('模拟读回一致')
 await page.getByRole('button',{name:'M2 调试与 SAT',exact:true}).click()
 await flow.getByLabel('自动测试场景',{exact:true}).selectOption('failure')
 await flow.getByLabel('模拟故障步骤',{exact:true}).selectOption('identity')
 await flow.getByRole('button',{name:'启动模拟 iEMS 自动测试',exact:true}).click()
 await expect(flow.locator('.m3Result')).toContainText('模拟故障')
 await expect(flow.locator('.m3Steps button').nth(4)).toContainText('等待前置验证')
 await flow.getByLabel('自动测试场景',{exact:true}).selectOption('normal')
 await flow.getByRole('button',{name:'启动模拟 iEMS 自动测试',exact:true}).click()
 await expect(flow.locator('.m3Complete')).toContainText('模拟 iEMS 自动测试完成')
 for(let i=0;i<5;i++)await expect(flow.locator('.m3Steps button').nth(i)).toContainText('✓ 模拟通过')
 await page.getByLabel('选择 iEMS 环境',{exact:true}).selectOption('REAL')
 await expect(flow.getByRole('button',{name:'启动真实 iEMS 自动测试',exact:true})).toBeDisabled()
 await expect(flow.locator('.m3Result')).toHaveCount(0)
 await page.getByRole('button',{name:'M1 系统建模与设置',exact:true}).click()
 await expect(config.getByRole('button',{name:'下发到真实 iEMS',exact:true})).toBeDisabled()
 await expect(config).toContainText('未获取真实生效值')
 await page.getByRole('button',{name:'M3 项目交接',exact:true}).click()
 await expect(page.getByRole('heading',{name:'项目交接',exact:true}).last()).toBeVisible()
 await page.getByRole('button',{name:'M4 现场服务',exact:true}).click()
 await expect(page.getByRole('heading',{name:'现场服务与厂家协同',exact:true})).toBeVisible()
})
